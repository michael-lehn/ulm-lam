def _flatten(x):
    if isinstance(x, (list, tuple)):
        for e in x:
            yield from _flatten(e)
    else:
        yield float(x)


def _shape(x):
    """(rows, cols) of a matrix argument; cols None if the buffer is flat
    (then only a vector's length is known)."""
    if _np is not None and isinstance(x, _np.ndarray):
        if x.ndim == 2:
            return x.shape
        if x.ndim == 1:
            return (x.shape[0], 1)
        return (x.size, None)
    if isinstance(x, (list, tuple)):
        if x and isinstance(x[0], (list, tuple)):
            return (len(x), len(x[0]))
        return (len(x), 1)
    mv = memoryview(x)
    if mv.ndim == 2:
        return mv.shape
    return (mv.nbytes // 8, None)


def _bind_sizes(env: dict, t: fe.MatrixType, x, what: str) -> None:
    """Take the run-time sizes of `t` from the argument `x` (and check the
    ones that are known)."""
    r, c = _shape(x)
    if c is None:  # a flat buffer: a vector, or a matrix of known size
        if t.cols == 1:
            c = 1
        elif isinstance(t.cols, int) and r % t.cols == 0:
            r, c = r // t.cols, t.cols
        elif isinstance(t.rows, int) and r % t.rows == 0:
            r, c = t.rows, r // t.rows
        else:
            raise fe.LamError(f"{what}: a flat buffer does not say the "
                               f"sizes of a {t} matrix; pass a NumPy array "
                               "or a list of rows")
    for d, v in ((t.rows, r), (t.cols, c)):
        if isinstance(d, str):
            if env.setdefault(d, v) != v:
                raise fe.LamError(f"{what}: size {d} = {v}, but {env[d]} "
                                   "from an earlier argument")
        elif d != v:
            raise fe.LamError(f"{what}: expected {t}, got {r}x{c}")


def _resolve(t: fe.MatrixType, env: dict) -> fe.MatrixType:
    """`t` with its run-time sizes replaced by their values."""
    return fe.MatrixType(env.get(t.rows, t.rows), env.get(t.cols, t.cols),
                         t.props, t.intent)


class _Arg:
    """A matrix argument as a C pointer (keeps its buffer alive)."""

    def __init__(self, x, rows: int, cols: int, writable: bool, what: str):
        n = rows * cols
        self.keep = x
        if _np is not None and isinstance(x, _np.ndarray):
            if x.dtype != _np.float64 or x.size != n:
                raise fe.LamError(f"{what}: expected {rows}x{cols} float64, "
                                   f"got {x.shape} {x.dtype}")
            if not x.flags["C_CONTIGUOUS"]:
                if writable:
                    raise fe.LamError(f"{what}: an inout matrix must be "
                                       "C-contiguous (it is written)")
                x = _np.ascontiguousarray(x)
            self.keep = x
            self.ptr = x.ctypes.data
            return
        if isinstance(x, (list, tuple)):
            if writable:
                raise fe.LamError(f"{what}: an inout matrix must be a "
                                   "writable buffer, not a list")
            x = array("d", _flatten(x))
        mv = memoryview(x)
        if mv.nbytes != 8 * n or mv.format not in ("d", "<d", "=d"):
            raise fe.LamError(f"{what}: expected {n} doubles ({rows}x{cols}),"
                               f" got {mv.nbytes} bytes of format "
                               f"{mv.format!r}")
        if mv.readonly:
            if writable:
                raise fe.LamError(f"{what}: an inout matrix must be "
                                   "writable")
            buf = (ctypes.c_double * n).from_buffer_copy(mv)
        else:
            buf = (ctypes.c_double * n).from_buffer(x)
        self.keep = (x, buf)
        self.ptr = ctypes.addressof(buf)


def _new_matrix(rows: int, cols: int):
    if _np is not None:
        return _np.empty((rows, cols))
    return array("d", [0.0]) * (rows * cols)


def _address(m) -> int:
    """The address of a matrix allocated by _new_matrix."""
    if _np is not None and isinstance(m, _np.ndarray):
        return m.ctypes.data
    return m.buffer_info()[0]


def _view(ptr: int, rows: int, cols: int):
    """The matrix at `ptr` (shared memory)."""
    if _np is not None:
        a = (ctypes.c_double * (rows * cols)).from_address(ptr)
        return _np.frombuffer(a, dtype=_np.float64).reshape(rows, cols)
    a = (ctypes.c_double * (rows * cols)).from_address(ptr)
    return memoryview(a).cast("B").cast("d", [rows, cols])


