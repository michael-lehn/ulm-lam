#!/usr/bin/env bash
# Reproduce the listings of the How-To; the outputs go to ../outputs.
# Run from anywhere:  doc/howto/examples/run.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
OUT="$HERE/../outputs"
mkdir -p "$OUT"
make -C "$ROOT" plugin tool >/dev/null
OPT="$ROOT/build/bin/ulm-lam-opt"
GEN="$ROOT/build/gen-plugin"

# 1. the frontend's IR (intermediate representation)
python3 "$HERE/gls.py" >"$OUT/1-traced.mlir"
# 2.-4. normal form, inferred properties, kernels (still with properties)
"$OPT" "$OUT/1-traced.mlir" \
	--pass-pipeline='builtin.module(func.func(ulm-lam-normalize))' \
	-o "$OUT/2-normal.mlir"
"$OPT" "$OUT/2-normal.mlir" \
	--pass-pipeline='builtin.module(func.func(ulm-lam-infer-properties))' \
	-o "$OUT/3-inferred.mlir"
"$OPT" "$OUT/3-inferred.mlir" \
	--pass-pipeline='builtin.module(func.func(ulm-lam-select-kernels), canonicalize)' \
	-o "$OUT/4-selected.mlir"
# 5.-7. the whole pipeline: bufferized, EmitC, C++
"$ROOT/scripts/ulm-lam-compile.sh" "$OUT/1-traced.mlir" "$OUT/gls"
mv "$OUT/gls.bufferized.mlir" "$OUT/5-bufferized.mlir"
"$OPT" "$OUT/gls.emitc.mlir" -o "$OUT/6-emitc.mlir"
mv "$OUT/gls.cpp" "$OUT/7-gls.cpp"
rm -f "$OUT/gls.selected.mlir" "$OUT/gls.emitc.mlir"

# 8. a rejected program: the verifier generated from the op definition
#    and the hand-written one
for f in "$HERE"/bad-*.mlir; do
	echo "### $(basename "$f")"
	"$OPT" "$f" -o /dev/null 2>&1 | sed "s|$HERE/||" || true
done >"$OUT/8-verify.out"

# 9. generated C++: excerpts of the declaration of ulm_lam.mul
awk '/^class MulOp : public/,/^};/' "$GEN/UlmLamOps.h.inc" >"$OUT/9-MulOp.h.inc"

# 10. sizes: what is written, what is generated
{
	echo "# hand-written TableGen"
	(cd "$ROOT/include/ulm_lam" && wc -l UlmLamBase.td UlmLamAttrs.td \
		UlmLamInterfaces.td UlmLamOps.td UlmLamKernelOps.td)
	echo "# generated by mlir-tblgen"
	(cd "$GEN" && wc -l *.inc)
	echo "# hand-written C++"
	(cd "$ROOT" && wc -l lib/*.cpp lib/*.h tools/ulm-lam.cpp)
} >"$OUT/10-sizes.out"

{
	echo "ulm-lam commit: $(git -C "$ROOT" rev-parse --short HEAD)"
	"$(brew --prefix llvm)/bin/mlir-opt" --version | sed -n 2p
} >"$OUT/versions.out"
echo "outputs in $OUT"
