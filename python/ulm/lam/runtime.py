def _ctype(t: str):
    if t.endswith("*") or "[" in t:
        return ctypes.c_void_p
    return {"size_t": ctypes.c_size_t, "int64_t": ctypes.c_int64,
            "double": ctypes.c_double, "bool": ctypes.c_bool}[t]


def _function_source(cpp: str, name: str) -> str:
    """The generated C++ of one function: its interface comment and its
    definition (up to the matching closing brace)."""
    start = cpp.find(f"/* {name}: matrices by reference")
    m = re.compile(rf'extern "C" \w+\n{name}\(').search(cpp, max(start, 0))
    if not m:
        return ""
    head = m.start()
    if start < 0 or start > head:
        start = head
    i = cpp.find("{", cpp.find(")", head))
    depth = 0
    for j in range(i, len(cpp)):
        if cpp[j] == "{":
            depth += 1
        elif cpp[j] == "}":
            depth -= 1
            if depth == 0:
                return cpp[start:j + 1] + "\n"
    return cpp[start:]


class Library:
    """A compiled ulm.lam module: its functions as attributes.

    lib.source         the whole generated C++ file
    lib.f.cpp          the generated C++ of function f
    """

    def __init__(self, path, ifaces, decls, functions, externs, cpp):
        self.path = path
        self.cpp = cpp
        self.source = Path(cpp).read_text()
        self._dll = ctypes.CDLL(str(path))
        self._decls = decls
        self._externs = externs
        self._callbacks = {}
        # the default workspace of the library's functions (reused)
        self.workspace = Workspace()
        self._workspace_busy = 0
        self._pending: list[BaseException] = []
        self.functions = {}
        for name, rows in ifaces.items():
            f = CompiledFunction(self, name, rows, functions.get(name))
            self.functions[name] = f
            setattr(self, name, f)

    def bind(self, **impls) -> None:
        """Implement external functions in Python."""
        for name, fn in impls.items():
            if name not in self._decls:
                raise fe.LamError(f"{name} is not an external function of "
                                   "this library")
            self._bind(name, fn)

    def _bind(self, name: str, fn) -> None:
        params = self._decls[name]
        ext = self._externs[name]
        cfun = ctypes.CFUNCTYPE(None, *[_ctype(t) for t in params])
        nparams = len(ext.params)
        out = ext.result is not None and ext.updates is None
        lib = self

        nsizes = len(ext.sizes)

        def tramp(*cargs):
            try:
                # run-time sizes: the leading size_t arguments
                env = dict(zip(ext.sizes, cargs[:nsizes]))
                cargs = cargs[nsizes:]
                args = []
                for k, p in enumerate(ext.params):
                    a = cargs[k]
                    if isinstance(p, fe.MatrixType):
                        p = _resolve(p, env)
                        args.append(_view(a, p.rows, p.cols))
                    else:
                        args.append(a)
                if ext.workspace:  # a Python callback needs no workspace
                    info = ctypes.c_int64.from_address(cargs[-1])
                    if info.value == -1:
                        info.value = 0
                        return
                r = fn(*args)
                if out:
                    t = _resolve(ext.result, env)
                    dst = _view(cargs[nparams], t.rows, t.cols)
                    _copy_into(dst, r, t, name)
            except BaseException as e:  # re-raised after the call
                lib._pending.append(e)

        cb = cfun(tramp)
        setter = getattr(self._dll, f"ulm_lam_set_{name}")
        setter.argtypes = [cfun]
        setter(cb)
        self._callbacks[name] = cb


def _copy_into(dst, r, t: fe.MatrixType, name: str) -> None:
    n = t.rows * t.cols
    if _np is not None and isinstance(dst, _np.ndarray):
        src = _np.asarray(r, dtype=_np.float64)
        if src.size != n:
            raise fe.LamError(f"{name} returned {src.size} values instead "
                               f"of {t}")
        dst[...] = src.reshape(t.rows, t.cols)
        return
    flat = memoryview(dst).cast("B").cast("d")
    vals = list(_flatten(r)) if isinstance(r, (list, tuple)) else \
        memoryview(r).cast("B").cast("d").tolist()
    if len(vals) != n:
        raise fe.LamError(f"{name} returned {len(vals)} values instead of "
                           f"{t}")
    for k, v in enumerate(vals):
        flat[k] = v


class Workspace:
    """Memory for the temporaries of compiled functions, 64-byte aligned
    (the workspace convention of the generated code, as LAPACK's work
    arrays).

        ws = lam.Workspace(lib.f.workspace_size(*args))
        lib.f(*args, work=ws)

    Every Library has one (lib.workspace) that its functions use by
    default; it grows as needed.  A workspace that is too small makes the
    call raise InfoError (info = -i)."""

    def __init__(self, size: int = 0):
        self._buf = None
        self.size = 0
        self.address = 0
        self.reserve(size)

    def reserve(self, size: int) -> None:
        """At least `size` bytes (contents are not kept)."""
        if size <= self.size:
            return
        buf = (ctypes.c_char * (size + 63))()
        self._buf = buf
        self.address = (ctypes.addressof(buf) + 63) & ~63
        self.size = size

    @classmethod
    def of(cls, array) -> "Workspace":
        """A workspace in a writable buffer (e.g. an int8 NumPy array)."""
        w = cls()
        mv = memoryview(array)
        if mv.readonly:
            raise fe.LamError("a workspace must be writable")
        if _np is not None and isinstance(array, _np.ndarray):
            if not array.flags["C_CONTIGUOUS"]:
                raise fe.LamError("a workspace must be contiguous")
            w.address = array.ctypes.data
        else:
            w.address = ctypes.addressof(
                (ctypes.c_char * mv.nbytes).from_buffer(array))
        w._buf = array
        w.size = mv.nbytes
        return w


class InfoError(fe.LamError):
    """A compiled function returned info != 0, as a LAPACK routine does:
    info = k > 0 if its check k failed (a factorisation: the matrix was not
    positive definite or singular, numerically, although the program
    assumed it; or a call of another ulm.lam function), info = -i if
    argument i was illegal.  The results are then unspecified."""

    def __init__(self, function: str, info: int, meaning: str):
        self.function, self.info, self.meaning = function, info, meaning
        super().__init__(f"{function}: info {info}"
                         + (f": {meaning}" if meaning else ""))


class CompiledFunction:
    """A ulm.lam function in a compiled library."""

    def __init__(self, lib: Library, name: str, rows, fn: fe.Function):
        self.lib, self.name, self.rows, self.fn = lib, name, rows, fn
        self._c = getattr(lib._dll, name)
        self._c.argtypes = [_ctype(t) for t, _ in rows]
        self._c.restype = ctypes.c_int64  # info, as LAPACK
        self._codes = _info_codes(lib.source).get(name, {})
        self._ws = {}
        self.has_workspace = bool(rows) and rows[-1][1] == "info"
        # run-time sizes: the leading size_t parameters
        self.sizes = list(fn.sizes) if fn else []
        self.__doc__ = self.interface()

    @property
    def cpp(self) -> str:
        """The generated C++ of this function (interface comment and
        definition; the helpers in front of it are in Library.source)."""
        return _function_source(self.lib.source, self.name)

    def interface(self) -> str:
        """The parameters and their intents (as the generated C++ says)."""
        lines = [f"{self.name}:"]
        if self.sizes:
            lines.append(f"  sizes {', '.join(self.sizes)}: from the "
                         "arrays")
        params = list(self.fn.params) if self.fn else []
        k = 0
        names = {f"v{j + 1}": x for j, x in enumerate(self.sizes)}
        for t, intent in self.rows[len(self.sizes):]:
            t = re.sub(r"\[(v\d+)\]",
                       lambda m: f"[{names.get(m.group(1), m.group(1))}]", t)
            if intent in ("in", "inout") and k < len(params):
                lines.append(f"  {params[k][0]:<10} {t:<22} {intent}")
                k += 1
            else:
                lines.append(f"  {'':<10} {t:<22} {intent}")
        return "\n".join(lines)

    def workspace_size(self, *args) -> int:
        """The workspace this call needs (bytes)."""
        env = self._sizes(args)
        key = tuple(env[x] for x in self.sizes) + tuple(
            a for a in args if isinstance(a, int))
        if key not in self._ws:
            info = ctypes.c_int64(-1)
            cargs, _, _ = self._arguments(args, query=True)
            self._c(*cargs, None, ctypes.addressof(info))
            self._ws[key] = info.value
        return self._ws[key]

    def _sizes(self, args) -> dict:
        """The run-time sizes, from the matrix arguments."""
        params = self.fn.params
        if len(args) != len(params):
            raise fe.LamError(f"{self.name} takes {len(params)} arguments "
                               f"({', '.join(n for n, _ in params)})")
        env = {}
        for a, (pname, pt) in zip(args, params):
            if isinstance(pt, fe.MatrixType) and pt.symbols():
                _bind_sizes(env, pt, a, f"{self.name}: {pname}")
        return env

    def _arguments(self, args, query=False):
        params = self.fn.params
        env = self._sizes(args)
        cargs, keep, outs = [env[x] for x in self.sizes], [], []
        k = 0
        results = [_resolve(t, env) for t in self.fn.results]
        for t, intent in self.rows[len(self.sizes):]:
            if intent in ("work", "info"):
                continue
            if intent == "out":
                rt = results.pop(0)
                m = _new_matrix(rt.rows, rt.cols)
                outs.append(m)
                cargs.append(None if query else _address(m))
                continue
            pname, pt = params[k]
            a = args[k]
            k += 1
            if isinstance(pt, fe.MatrixType):
                pt = _resolve(pt, env)
                if query:
                    cargs.append(None)
                    continue
                arg = _Arg(a, pt.rows, pt.cols, intent == "inout",
                           f"{self.name}: {pname}")
                keep.append(arg)
                cargs.append(arg.ptr)
            else:
                if not isinstance(a, int) or a < 0:
                    raise fe.LamError(f"{self.name}: {pname} must be a "
                                       "non-negative int")
                cargs.append(a)
        # the caller keeps `keep` alive while C uses the pointers
        return cargs, outs, keep

    def __call__(self, *args, work=None):
        """Call the function.  work: a Workspace (or a writable int8 NumPy
        array) for its temporaries; by default the library's workspace,
        which grows as needed and is reused by later calls."""
        cargs, outs, keep = self._arguments(args)
        lib = self.lib
        borrowed = False
        if self.has_workspace:
            size = self.workspace_size(*args)
            if work is None:
                if lib._workspace_busy:  # a call from a callback
                    work = Workspace(size)
                else:
                    work = lib.workspace
                    work.reserve(size)
                    borrowed = True
            elif not isinstance(work, Workspace):
                work = Workspace.of(work)
            # too small: the function returns info = -i (InfoError)
            info = ctypes.c_int64(max(work.size, 1))
            cargs += [work.address, ctypes.addressof(info)]
            keep.append(work)
        lib._pending.clear()
        lib._workspace_busy += borrowed
        try:
            info = self._c(*cargs)
        finally:
            lib._workspace_busy -= borrowed
        del keep  # the argument buffers lived until here
        if self.lib._pending:
            raise self.lib._pending[0]
        if info != 0:
            raise InfoError(self.name, info, self._codes.get(info, ""))
        if not outs:
            return None
        return outs[0] if len(outs) == 1 else tuple(outs)
