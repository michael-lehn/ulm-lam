"""lam.runtime: compile ulm.lam functions and call them from Python.

    lib = lam.compile(gls)                  # or a list of functions
    b = lib.gls(X, M, y)                     # arrays in, arrays out

lam.compile runs the ulm.lam pipeline (scripts/ulm-lam-compile.sh: kernel
selection, bufferization, workspaces, lowering to C++ calling ulmBLAS),
builds a shared library and returns its functions as Python callables.
An unchanged program reuses its library as long as compiler, ulmBLAS
and flags are unchanged (set ULM_LAM_REBUILD=1 to force a rebuild); the files are in build/python/<name>/.

Calling convention, from the interface comment the compiler generates in
front of every function:
  * in matrices: any C-contiguous float64 buffer of the right size (NumPy
    arrays, array.array('d'), ...), or nested lists; never written;
  * inout matrices: a writable C-contiguous float64 buffer; the function
    may overwrite it (with lam.update it holds the updated value);
  * out matrices (the return values): allocated here and returned;
  * index parameters: Python ints;
  * the workspace: queried (workspace_info = -1) and allocated here, once
    per distinct index arguments.

External functions can be implemented in Python:
    lib.bind(observe=lambda i: ..., record=lambda i, b: ...)
The compiler generates C trampolines for them.  Matrix arguments arrive as
NumPy arrays (if NumPy is installed) or as memoryviews of shape (rows, cols)
that share the memory with the caller; a returned matrix (the result of the
external function) may be any buffer, NumPy array or nested list.  An
exception in a callback is re-raised when the ulm.lam function returns.

Environment: LLVM_PREFIX (Homebrew llvm), ULMBLAS_DIR (default
~/git/ulmBLAS), ARCHFLAGS (default -mcpu=native), CXX (default c++).
"""

