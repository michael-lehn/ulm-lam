# runtime.jl: compile ulm.lam functions and call them from Julia.
#
#     lib = UlmLam.compile([gls])        # ulm_lam IR -> C++ -> shared library
#     b = lib.gls(X, M, y)               # Julia arrays in and out
#
# compile runs the ulm.lam pipeline (scripts/ulm-lam-compile.sh), builds a
# shared library and returns its functions.  An unchanged program reuses
# its library (named after a hash of program, compiler and flags).
#
# Calling convention (from the interface comment the compiler generates):
#   * matrices: Matrix{Float64} (column-major; passed as the row-major
#     transpose, no copy), vectors: Vector{Float64}; `in` arguments of
#     another type are converted, InOut ones must be Matrix{Float64};
#   * Index arguments: Int >= 0, Float arguments: numbers;
#   * results: allocated here and returned;
#   * the workspace: queried and allocated here, 64-byte aligned, reused.
#
# Backends: :julia (default) calls Julia's BLAS and LAPACK through
# libblastrampoline (OpenBLAS, or ulmBLAS after UlmBLAS.forward()), :ulmblas
# the header-only ulmBLAS (ULMBLAS_DIR), :cblas a CBLAS/LAPACK library
# (ULM_LAM_BLAS_LIBS, default Homebrew's OpenBLAS).
# Environment: LLVM_PREFIX, ULMBLAS_DIR (default ~/git/ulmBLAS), ARCHFLAGS
# (default -mcpu=native), CXX (default c++), OPENMP (0: without).

const ROOT = normpath(joinpath(@__DIR__, "..", "..", ".."))

# ---------------------------------------------------------------------------
# Compilation
# ---------------------------------------------------------------------------

function run_or_fail(cmd::Cmd, what)
    out = IOBuffer()
    ok = success(pipeline(cmd; stdout=out, stderr=out))
    ok || throw(LamError("$what failed:\n" * String(take!(out))))
    nothing
end

function openmp_flags()
    get(ENV, "OPENMP", "1") == "1" || return String[]
    Sys.isapple() || return ["-fopenmp"]
    omp = "/opt/homebrew/opt/libomp"
    isdir(omp) || return String[]
    ["-Xpreprocessor", "-fopenmp", "-isystem", "$omp/include",
     "-L$omp/lib", "-Wl,-rpath,$omp/lib", "-lomp"]
end

"""The libblastrampoline Julia has loaded (its BLAS: OpenBLAS by default, or
whatever it forwards to, e.g. ulmBLAS after UlmBLAS.forward())."""
lbt_path() = Libdl.dlpath(LinearAlgebra.BLAS.libblastrampoline)

function cxx_flags(backend::Symbol)
    arch = split(get(ENV, "ARCHFLAGS", "-mcpu=native"))
    if backend == :julia
        lbt = lbt_path()
        return ["-std=c++17", "-O3", arch..., "-I", joinpath(ROOT, "include"),
                "-DULM_LAM_CBLAS_ILP64", lbt, "-Wl,-rpath," * dirname(lbt)]
    end
    if backend == :cblas
        libs = haskey(ENV, "ULM_LAM_BLAS_LIBS") ? split(ENV["ULM_LAM_BLAS_LIBS"]) :
               isdir("/opt/homebrew/opt/openblas/lib") ?
               ["-L/opt/homebrew/opt/openblas/lib",
                "-Wl,-rpath,/opt/homebrew/opt/openblas/lib", "-lopenblas"] :
               ["-lopenblas"]
        return ["-std=c++17", "-O3", arch..., "-I", joinpath(ROOT, "include"), libs...]
    end
    ulm = get(ENV, "ULMBLAS_DIR", joinpath(homedir(), "git", "ulmBLAS"))
    isfile(joinpath(ulm, "ulmblas", "ulmblas.h")) ||
        throw(LamError("ulmBLAS not found: set ULMBLAS_DIR (now $ulm)"))
    ["-std=c++17", "-O3", arch..., "-isystem", ulm, openmp_flags()...]
end

"""Modification time of the newest part of the compiler and of the
headers the C++ depends on."""
function newest(backend::Symbol)
    files = String[]
    for d in (joinpath(ROOT, "lib"), joinpath(ROOT, "scripts"),
              joinpath(ROOT, "include", "ulm_lam"), @__DIR__)
        append!(files, joinpath.(d, readdir(d)))
    end
    if backend == :ulmblas
        ulm = joinpath(get(ENV, "ULMBLAS_DIR", joinpath(homedir(), "git", "ulmBLAS")), "ulmblas")
        for (r, _, fs) in walkdir(ulm), f in fs
            push!(files, joinpath(r, f))
        end
    end
    maximum(mtime, files)
end

function trampolines(decls::Dict{String,Vector{String}})
    lines = ["// generated by ulm.lam: Julia callbacks for external functions",
             "#include <cstddef>", "#include <cstdint>", "#include <cstdio>",
             "#include <cstdlib>", "", "extern \"C\" {"]
    for (name, params) in decls
        sig = join(params, ", ")
        args = join(["$t a$k" for (k, t) in enumerate(params)], ", ")
        names = join(["a$k" for k in 1:length(params)], ", ")
        append!(lines, [
            "static void (*ulm_lam_cb_$name)($sig) = nullptr;",
            "void ulm_lam_set_$name(void (*f)($sig)) { ulm_lam_cb_$name = f; }",
            "void $name($args)", "{",
            "    if (!ulm_lam_cb_$name) {",
            "        std::fprintf(stderr, \"ulm.lam: external function $name is not bound (bind!)\\n\");",
            "        std::abort();", "    }",
            "    ulm_lam_cb_$name($names);", "}", ""])
    end
    push!(lines, "}")
    join(lines, "\n") * "\n"
end

# ---------------------------------------------------------------------------
# The generated interface
# ---------------------------------------------------------------------------

const IFACE = r"/\* (\w+): matrices by reference[^\n]*\n(.*?)\n \*/"s
const SIG = r"extern \"C\" void\s*\n(\w+)\(([^)]*)\);"

"""name => [(C type, intent)] from the interface comments."""
function interfaces(cpp::String)
    out = Dict{String,Vector{Tuple{String,String}}}()
    for m in eachmatch(IFACE, cpp)
        rows = Tuple{String,String}[]
        for line in split(split(m.captures[2], " * returns info:")[1], '\n')
            parts = split(lstrip(line, [' ', '*']))
            isempty(parts) && continue
            ctype = parts[2] * (length(parts) > 2 && parts[3] == "*" ? " *" : "")
            intent = endswith(ctype, "*") ? parts[4] : (length(parts) > 2 ? parts[3] : "in")
            push!(rows, (ctype, intent))
        end
        out[m.captures[1]] = rows
    end
    out
end

"""name => Dict(info => meaning), wrapped lines joined."""
function info_codes(cpp::String)
    out = Dict{String,Dict{Int,String}}()
    for m in eachmatch(IFACE, cpp)
        codes = Dict{Int,String}()
        parts = split(m.captures[2], " * returns info:")
        last = nothing
        if length(parts) > 1
            for line in split(parts[2], '\n')
                c = match(r"^\s*(-?\d+)\s+(.*)$", lstrip(line, [' ', '*']))
                if c !== nothing
                    last = parse(Int, c.captures[1])
                    codes[last] = c.captures[2]
                elseif last !== nothing && startswith(line, " *   ") &&
                       !startswith(line, " * (")
                    codes[last] *= " " * strip(line, [' ', '*'])
                end
            end
        end
        out[m.captures[1]] = codes
    end
    out
end

function declarations(cpp::String)
    Dict(String(m.captures[1]) => [String(strip(p)) for p in split(m.captures[2], ',') if !isempty(strip(p))]
         for m in eachmatch(SIG, cpp))
end

ctype(t) = endswith(t, "*") || occursin('[', t) ? Ptr{Cvoid} :
           Dict("size_t" => Csize_t, "int64_t" => Int64, "double" => Cdouble,
                "bool" => Bool)[t]

