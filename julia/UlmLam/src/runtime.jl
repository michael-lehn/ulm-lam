"""A compiled function returned info != 0, as a LAPACK routine does: k > 0
if its check k failed (a factorisation), -i if argument i was illegal."""
struct InfoError <: Exception
    func::String
    info::Int
    meaning::String
end
Base.showerror(io::IO, e::InfoError) =
    print(io, "InfoError: $(e.func): info $(e.info)", isempty(e.meaning) ? "" : ": $(e.meaning)")

"""Memory for the temporaries of compiled functions, 64-byte aligned."""
mutable struct Workspace
    buf::Vector{UInt8}
    size::Int
end
Workspace(size::Integer=0) = (w = Workspace(UInt8[], 0); reserve!(w, size); w)
function reserve!(w::Workspace, size::Integer)
    size <= w.size && return w
    w.buf = Vector{UInt8}(undef, size + 64)
    w.size = size
    w
end
address(w::Workspace) = (p = UInt(pointer(w.buf)); Ptr{Cvoid}((p + 63) & ~UInt(63)))

struct CompiledFunction
    lib::Any
    name::String
    rows::Vector{Tuple{String,String}}
    fn::LamFunction
    call::Function
    codes::Dict{Int,String}
    has_workspace::Bool
end

mutable struct Library
    path::String
    source::String
    handle::Ptr{Cvoid}
    functions::Dict{Symbol,CompiledFunction}
    externs::Dict{Symbol,Extern}
    decls::Dict{String,Vector{String}}
    callbacks::Dict{Symbol,Any}
    workspace::Workspace
    pending::Vector{Any}
end

function Base.getproperty(lib::Library, s::Symbol)
    s in fieldnames(Library) && return getfield(lib, s)
    fs = getfield(lib, :functions)
    haskey(fs, s) && return fs[s]
    throw(LamError("the library has no function $s"))
end
Base.propertynames(lib::Library) = (fieldnames(Library)..., keys(lib.functions)...)

"""The generated C++ of a compiled function (interface comment and
definition)."""
function cpp(f::CompiledFunction)
    src = f.lib.source
    start = findfirst("/* $(f.name): matrices by reference", src)
    m = match(Regex("extern \"C\" \\w+\\n$(f.name)\\("), src)
    (start === nothing || m === nothing) && return ""
    i = findnext('{', src, findnext(')', src, m.offset))
    depth = 0
    for j in i:lastindex(src)
        src[j] == '{' && (depth += 1)
        if src[j] == '}'
            depth -= 1
            depth == 0 && return src[first(start):j] * "\n"
        end
    end
    src[first(start):end]
end

"""
    compile(functions; name, backend=:ulmblas) -> Library

Compile ulm.lam functions into a shared library.  backend=:cblas runs the
same kernel calls on CBLAS/LAPACK (OpenBLAS by default).
"""
function compile(functions::Vector{LamFunction}; name::AbstractString=string(functions[1].name),
                 backend::Symbol=Symbol(get(ENV, "ULM_LAM_BACKEND", "julia")))
    backend in (:julia, :ulmblas, :cblas) ||
        throw(LamError("backend must be :julia, :ulmblas or :cblas"))
    work = joinpath(ROOT, "build", "julia", name)
    mkpath(work)
    text, externs = lam_module(functions)
    flags = cxx_flags(backend)
    key = bytes2hex(sha256(text * "\n" * string(newest(backend)) * "\n" *
                           get(ENV, "CXX", "c++") * " " * string(backend) * " " * join(flags, " ")))
    lib = joinpath(work, "lib$name.$(key[1:12]).$(Libdl.dlext)")
    mlirfile = joinpath(work, "$name.mlir")
    write(mlirfile, text)
    cppfile = joinpath(work, "$name.cpp")
    # the kernels after selection, for @code_lam (kept per program)
    selected = joinpath(work, "$name.$(key[1:12]).selected.mlir")
    cached = !haskey(ENV, "ULM_LAM_REBUILD") && isfile(lib) && isfile(selected)
    if !cached
        script = joinpath(ROOT, "scripts", "ulm-lam-compile.sh")
        irbackend = backend == :ulmblas ? "ulmblas" : "cblas"  # :julia is CBLAS too
        run_or_fail(addenv(`$script $mlirfile $(joinpath(work, name))`, "BACKEND" => irbackend),
                    "ulm-lam-compile")
        cp(joinpath(work, "$name.selected.mlir"), selected; force=true)
    end
    src = read(cppfile, String)
    ifaces = interfaces(src)
    decls = Dict(k => v for (k, v) in declarations(src) if !haskey(ifaces, k))
    sources = [cppfile]
    if !isempty(decls)
        tramp = joinpath(work, "$(name)_externs.cpp")
        write(tramp, trampolines(decls))
        push!(sources, tramp)
    end
    if !cached
        partial = lib * ".partial"
        cxx = get(ENV, "CXX", "c++")
        run_or_fail(`$cxx -shared -fPIC $sources $flags -o $partial`, "C++ compilation")
        mv(partial, lib; force=true)
        for f in readdir(work)
            if startswith(f, "lib$name.") && joinpath(work, f) != lib
                rm(joinpath(work, f); force=true)
            end
        end
    end
    handle = Libdl.dlopen(lib)
    L = Library(lib, src, handle, Dict{Symbol,CompiledFunction}(), externs, decls,
                Dict{Symbol,Any}(), Workspace(), Any[])
    codes = info_codes(src)
    byname = Dict(string(f.name) => f for f in functions)
    for (fname, rows) in ifaces
        haskey(byname, fname) || continue
        fptr = Libdl.dlsym(handle, fname)
        types = [ctype(t) for (t, _) in rows]
        argnames = [Symbol("a$k") for k in 1:length(types)]
        caller = eval(:(($(argnames...),) -> ccall($fptr, Int64, ($(types...),), $(argnames...))))
        L.functions[Symbol(fname)] = CompiledFunction(L, fname, rows, byname[fname], caller,
                                                       get(codes, fname, Dict{Int,String}()),
                                                       !isempty(rows) && rows[end][2] == "info")
    end
    L
end
compile(f::LamFunction; kw...) = compile([f]; kw...)

# -- arguments ---------------------------------------------------------------

jsize(x::AbstractVector) = (length(x), 1)
jsize(x::AbstractMatrix) = size(x)

function bind_sizes!(env::Dict{Symbol,Int}, t::MatType, x, what)
    (x isa AbstractVecOrMat) || throw(LamError("$what: expected an array, got $(typeof(x))"))
    r, c = jsize(x)
    for (d, v) in ((t.rows, r), (t.cols, c))
        if d isa Symbol
            get!(env, d, v) == v ||
                throw(LamError("$what: size :$d = $v, but $(env[d]) from an earlier argument"))
        elseif d != v
            throw(LamError("$what: expected $t, got $r x $c"))
        end
    end
end

resolve(t::MatType, env) = (get(env, t.rows, t.rows), get(env, t.cols, t.cols))
resolve_dim(d, env) = d isa Symbol ? env[d] : d

function sizes_of(f::CompiledFunction, args)
    params = f.fn.params
    length(args) == length(params) ||
        throw(LamError("$(f.name) takes $(length(params)) arguments " *
                       "($(join(first.(params), ", ")))"))
    env = Dict{Symbol,Int}()
    for (a, (n, t)) in zip(args, params)
        t isa MatType && bind_sizes!(env, t, a, "$(f.name): $n")
    end
    env
end

"""The arguments of the C call (and what must stay alive)."""
function arguments(f::CompiledFunction, args, query::Bool)
    env = sizes_of(f, args)
    cargs = Any[Csize_t(env[x]) for x in f.fn.sizes]
    keep, outs = Any[], Any[]
    results = copy(f.fn.results)
    k = 1
    for (t, intent) in f.rows[length(f.fn.sizes)+1:end]
        intent in ("work", "info") && continue
        if intent == "out"
            rt = popfirst!(results)
            r, c = resolve_dim(rt.rows, env), resolve_dim(rt.cols, env)
            m = rt.isvec ? Vector{Float64}(undef, r) : Matrix{Float64}(undef, r, c)
            push!(outs, m)
            push!(cargs, query ? C_NULL : Ptr{Cvoid}(pointer(m)))
            continue
        end
        pname, pt = f.fn.params[k]
        a = args[k]
        k += 1
        if pt isa MatType
            if query
                push!(cargs, C_NULL)
                continue
            end
            if intent == "inout"
                a isa Array{Float64} ||
                    throw(LamError("$(f.name): $pname is InOut: it must be an Array{Float64} (it is written)"))
            elseif !(a isa Array{Float64})
                a = Array{Float64}(a)  # converted (a copy) for reading
            end
            push!(keep, a)
            push!(cargs, Ptr{Cvoid}(pointer(a)))
        elseif pt isa FloatType
            a isa Real || throw(LamError("$(f.name): $pname must be a number"))
            push!(cargs, Cdouble(a))
        else
            (a isa Integer && a >= 0) ||
                throw(LamError("$(f.name): $pname must be a non-negative integer"))
            push!(cargs, Csize_t(a))
        end
    end
    cargs, outs, keep
end

"""The workspace a call needs (bytes)."""
function workspace_size(f::CompiledFunction, args...)
    f.has_workspace || return 0
    cargs, _, keep = arguments(f, args, true)
    info = Ref{Int64}(-1)
    GC.@preserve keep info begin
        Base.invokelatest(f.call, cargs..., C_NULL,
                          Ptr{Cvoid}(Base.unsafe_convert(Ptr{Int64}, info)))
    end
    Int(info[])
end

function (f::CompiledFunction)(args...; work::Union{Workspace,Nothing}=nothing)
    lib = f.lib
    cargs, outs, keep = arguments(f, args, false)
    info = Ref{Int64}(0)
    if f.has_workspace
        size = workspace_size(f, args...)
        work = work === nothing ? reserve!(lib.workspace, size) : work
        info[] = max(work.size, 1)
        push!(cargs, address(work), Ptr{Cvoid}(Base.unsafe_convert(Ptr{Int64}, info)))
        push!(keep, work)
    end
    empty!(lib.pending)
    # (the ccall wrapper was created by eval: newer than the caller's world)
    r = GC.@preserve keep info outs Base.invokelatest(f.call, cargs...)
    isempty(lib.pending) || throw(lib.pending[1])
    r == 0 || throw(InfoError(f.name, Int(r), get(f.codes, Int(r), "")))
    isempty(outs) ? nothing : length(outs) == 1 ? outs[1] : Tuple(outs)
end

Base.show(io::IO, f::CompiledFunction) = print(io, "compiled ", f.fn)

# -- callbacks -----------------------------------------------------------------

"""A row-major buffer of the generated code as a Julia array of the logical
shape: a vector, or the lazy transpose of the column-major view."""
function view_of(p::Ptr{Cvoid}, t::MatType, env)
    r, c = resolve_dim(t.rows, env), resolve_dim(t.cols, env)
    c == 1 && return unsafe_wrap(Array, Ptr{Float64}(p), r)
    transpose(unsafe_wrap(Array, Ptr{Float64}(p), (c, r)))
end

"""
    bind!(lib; name = f, ...)

Implement the external functions of the library in Julia.
"""
function bind!(lib::Library; impls...)
    for (name, fn) in impls
        sname = string(name)
        haskey(lib.decls, sname) || throw(LamError("$name is not an external function of this library"))
        ext = lib.externs[name]
        params = lib.decls[sname]
        sizes = ext_sizes(ext)
        nsizes = length(sizes)
        np = length(ext.params)
        L = lib
        tramp = function (cargs...)
            try
                env = Dict{Symbol,Int}(zip(sizes, Int.(cargs[1:nsizes])))
                rest = cargs[nsizes+1:end]
                args = Any[]
                for (k, p) in enumerate(ext.params)
                    a = rest[k]
                    push!(args, p isa MatType ? view_of(a, p, env) : p isa IndexType ? Int(a) : a)
                end
                r = fn(args...)
                if ext.result !== nothing
                    dst = view_of(rest[np+1], ext.result, env)
                    size(dst) == size(r) ||
                        throw(LamError("$name returned $(size(r)) instead of $(size(dst))"))
                    dst .= r
                end
            catch e
                push!(L.pending, e)
            end
            nothing
        end
        types = Tuple(ctype(t) for t in params)
        # a closure: @cfunction($tramp, ...), the $ kept in the expression
        cf = eval(Expr(:macrocall, Symbol("@cfunction"), LineNumberNode(0),
                       Expr(:$, tramp), Cvoid, Expr(:tuple, types...)))
        setter = Libdl.dlsym(lib.handle, "ulm_lam_set_$sname")
        ccall(setter, Cvoid, (Ptr{Cvoid},), cf)
        lib.callbacks[name] = cf  # keep it alive
    end
    lib
end

# -- calling a @lam function directly -----------------------------------------

const JIT = IdDict{LamFunction,Library}()

"""
    library(f) -> Library

The library of the ulm.lam function f, compiled at its first call (with the
backend from ULM_LAM_BACKEND, default :julia) and kept.
"""
library(f::LamFunction) = get!(() -> compile(f), JIT, f)

"""
    f(args...; work=nothing)

Call the ulm.lam function f with Julia arrays: compiled at the first call.
"""
(f::LamFunction)(args...; work::Union{Workspace,Nothing}=nothing) =
    getproperty(library(f), f.name)(args...; work=work)

"""
    bind!(f; name = g, ...)

Implement the external functions that the ulm.lam function f calls.
"""
bind!(f::LamFunction; impls...) = bind!(library(f); impls...)
