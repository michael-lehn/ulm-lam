def _run(cmd: list[str], what: str) -> None:
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        raise fe.LamError(f"{what} failed:\n{p.stdout}{p.stderr}")


def _ulmblas_flags() -> list[str]:
    ulm = Path(os.environ.get("ULMBLAS_DIR", Path.home() / "git" / "ulmBLAS"))
    if not (ulm / "ulmblas" / "ulmblas.h").exists():
        raise fe.LamError(f"ulmBLAS not found: set ULMBLAS_DIR (now {ulm})")
    arch = os.environ.get("ARCHFLAGS", "-mcpu=native").split()
    return ["-std=c++17", "-O3", *arch, "-isystem", str(ulm)]


_SIG = re.compile(r'extern "C" void\s*\n(\w+)\(([^)]*)\);')
_IFACE = re.compile(r"/\* (\w+): matrices by reference[^\n]*\n(.*?)\n \*/",
                    re.S)


def _interfaces(cpp: str) -> dict[str, list[tuple[str, str]]]:
    """name -> [(C type, intent)] from the generated interface comments."""
    out = {}
    for m in _IFACE.finditer(cpp):
        rows = []
        for line in m.group(2).splitlines():
            parts = line.lstrip(" *").split()
            # v1  double[2000][200]  in  read only  |  v5  int8_t *  work ...
            ctype = parts[1] + (" *" if len(parts) > 2 and parts[2] == "*"
                                else "")
            intent = parts[3] if ctype.endswith("*") else (
                parts[2] if len(parts) > 2 else "in")
            rows.append((ctype, intent))
        out[m.group(1)] = rows
    return out


def _declarations(cpp: str) -> dict[str, list[str]]:
    """External functions: name -> [C parameter types]."""
    out = {}
    for m in _SIG.finditer(cpp):
        params = [p.strip() for p in m.group(2).split(",") if p.strip()]
        out[m.group(1)] = params
    return out


def _trampolines(decls: dict[str, list[str]]) -> str:
    lines = ["// generated by ulm.lam: Python callbacks for external functions",
             "#include <cstddef>", "#include <cstdint>", "#include <cstdio>",
             "#include <cstdlib>", "", 'extern "C" {']
    for name, params in decls.items():
        sig = ", ".join(params)
        args = ", ".join(f"{t} a{k}" for k, t in enumerate(params))
        names = ", ".join(f"a{k}" for k in range(len(params)))
        lines += [
            f"static void (*ulm_lam_cb_{name})({sig}) = nullptr;",
            f"void ulm_lam_set_{name}(void (*f)({sig})) {{ ulm_lam_cb_{name} = f; }}",
            f"void {name}({args})",
            "{",
            f"    if (!ulm_lam_cb_{name}) {{",
            f'        std::fprintf(stderr, "ulm.lam: external function {name} '
            f'is not bound (Library.bind)\\n");',
            "        std::abort();",
            "    }",
            f"    ulm_lam_cb_{name}({names});",
            "}",
            "",
        ]
    lines.append("}")
    return "\n".join(lines) + "\n"


def _newest_tool() -> float:
    """Modification time of the newest part of the compiler (a cached
    library older than that is rebuilt)."""
    parts = [*ROOT.joinpath("lib").glob("*"), *ROOT.joinpath("scripts").glob("*"),
             *ROOT.joinpath("include", "ulm_lam").glob("*"),
             *Path(__file__).parent.glob("*.py")]
    return max(p.stat().st_mtime for p in parts)


def compile(functions, name: str | None = None, workdir=None,
            externs: dict | None = None) -> "Library":
    """Compile ulm.lam functions (and what they call) into a library."""
    if isinstance(functions, fe.Function):
        functions = [functions]
    functions = list(functions)
    name = name or functions[0].name
    work = Path(workdir) if workdir else ROOT / "build" / "python" / name
    work.mkdir(parents=True, exist_ok=True)
    mlir = work / f"{name}.mlir"
    text = fe.module(functions)
    ext = ".dylib" if sys.platform == "darwin" else ".so"
    # The library is named after its program and the compiler version
    # (the newest part of the compiler), so that
    #  * an unchanged program reuses its library (C++ compilation of the
    #    ulmBLAS templates takes seconds),
    #  * a changed program never meets an old library, also not one that a
    #    process has already loaded (dlopen returns the loaded image for a
    #    path it knows), and
    #  * an interrupted build leaves no library: it is built under a
    #    temporary name and renamed when complete.
    key = hashlib.sha256(f"{text}\n{_newest_tool()}".encode()).hexdigest()
    lib = work / f"lib{name}.{key[:12]}{ext}"
    cached = not os.environ.get("ULM_LAM_REBUILD") and lib.exists()
    mlir.write_text(text)
    if not cached:
        _run([str(ROOT / "scripts" / "ulm-lam-compile.sh"), str(mlir),
              str(work / name)], "ulm-lam-compile")
    cpp = (work / f"{name}.cpp").read_text()
    ifaces = _interfaces(cpp)
    decls = {n: p for n, p in _declarations(cpp).items()
             if n not in ifaces and n != "ulm_lam_workspace_error"}
    sources = [str(work / f"{name}.cpp")]
    if decls:
        tramp = work / f"{name}_externs.cpp"
        tramp.write_text(_trampolines(decls))
        sources.append(str(tramp))
    if not cached:
        cxx = os.environ.get("CXX", "c++")
        partial = lib.with_name(lib.name + ".partial")
        _run([cxx, *_ulmblas_flags(), "-shared", "-fPIC", *sources, "-o",
              str(partial)], "C++ compilation")
        partial.replace(lib)
        for old in work.glob(f"lib{name}.*{ext}"):
            if old != lib:
                old.unlink(missing_ok=True)
    # the program's functions and externs, by name
    prog_fns = {}
    todo = list(functions)
    while todo:
        f = todo.pop()
        if f.name not in prog_fns:
            prog_fns[f.name] = f
    library = Library(lib, ifaces, decls, prog_fns, _externs_of(functions),
                      work / f"{name}.cpp")
    if externs:
        library.bind(**externs)
    return library


def _externs_of(functions) -> dict[str, fe.Extern]:
    prog = fe._Program()
    outer = fe._Program.current
    fe._Program.current = prog
    try:
        for f in functions:
            f._text = None
            f.trace()
            prog.functions.append(f)
        i = 0
        while i < len(prog.functions):
            prog.functions[i]._text = None
            prog.functions[i].trace()
            i += 1
    finally:
        fe._Program.current = outer
    return prog.externs


